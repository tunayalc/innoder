export const language: 'tr' | 'en' = (() => {
  if (typeof window !== 'undefined') {
    const query = new URLSearchParams(window.location?.search).get('lang');
    if (query === 'en' || query === 'tr') return query;
  }
  try {
    return localStorage.getItem('inno_lang') === 'en' ? 'en' : 'tr';
  } catch {
    return 'tr';
  }
})();
export const translate = (source: string) =>
  language === 'en' && Object.prototype.hasOwnProperty.call(english, source)
    ? english[source]
    : source;
